#!/usr/bin/env node
/**
 * Pull the authoritative App Store facts into lib/appstore.generated.ts.
 *
 * The site kept drifting from the listing - it advertised $1.99 when Plus is
 * $5.99, and iOS 17+ when the app requires 26.5. Anything Apple publishes is
 * fetched here rather than typed by hand, so the next drift is a diff instead
 * of a discovery.
 *
 * Run after every App Store release:  npm run sync:appstore
 *
 * Not covered: in-app purchase prices. Apple exposes no public API for them, so
 * tiers and pack prices in lib/site.ts are mirrored from privamesh.storekit in
 * the app repo and must be re-checked in App Store Connect by hand.
 */

import fs from 'node:fs'

const APP_ID = '6785997584'
const OUT = 'lib/appstore.generated.ts'

const res = await fetch(`https://itunes.apple.com/lookup?id=${APP_ID}&country=us`)
if (!res.ok) {
  console.error(`Lookup failed: HTTP ${res.status}`)
  process.exit(1)
}
const json = await res.json()
if (!json.resultCount) {
  console.error('Lookup returned no results - is the app still published?')
  process.exit(1)
}

const r = json.results[0]
const data = {
  name: r.trackName,
  seller: r.sellerName,
  bundleId: r.bundleId,
  version: r.version,
  minimumOsVersion: r.minimumOsVersion,
  price: String(r.price),
  formattedPrice: r.formattedPrice,
  currency: r.currency,
  primaryGenre: r.primaryGenreName,
  contentRating: r.contentAdvisoryRating,
  releasedAt: r.releaseDate,
  updatedAt: r.currentVersionReleaseDate,
  languages: r.languageCodesISO2A,
  // Deliberately not written: averageUserRating and userRatingCount. They are 0
  // here, and a rating must never reach the page or the schema until it is real.
}

const file = `// Generated by scripts/sync-appstore.mjs - do not edit by hand.
// Source: https://itunes.apple.com/lookup?id=${APP_ID}
// Last synced: ${new Date().toISOString()}

export const APP_STORE = ${JSON.stringify(data, null, 2)} as const
`

const previous = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
fs.writeFileSync(OUT, file)

const strip = (s) => s.replace(/^\/\/ Last synced:.*$/m, '')
if (strip(previous) === strip(file)) {
  console.log('App Store data unchanged.')
} else {
  console.log('App Store data updated:')
  for (const [k, v] of Object.entries(data)) console.log(`  ${k.padEnd(18)} ${JSON.stringify(v)}`)
  if (previous) console.log('\nReview the diff before committing.')
}

if (r.userRatingCount > 0) {
  console.log(
    `\nNOTE: the listing now has ${r.userRatingCount} rating(s), average ${r.averageUserRating}.` +
      '\nSITE.rating in lib/site.ts can be filled in, which turns on the AggregateRating schema.',
  )
}
